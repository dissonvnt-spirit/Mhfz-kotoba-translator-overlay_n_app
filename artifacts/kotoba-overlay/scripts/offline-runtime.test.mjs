import assert from 'node:assert/strict';
import { mkdtempSync, writeFileSync, readFileSync, readdirSync, rmSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { test } from 'node:test';
import runtime from './offline-runtime.cjs';
import verifier from './verify-offline-runtime.cjs';

test('the audited dependency versions and both JSEP assets are installed', () => {
  const directory = runtime.runtimeDirectory();
  for (const name of runtime.RUNTIME_FILES) assert.ok(readFileSync(path.join(directory, name)).length > 0);
  assert.equal(runtime.TRANSFORMERS_VERSION, '3.8.1');
});

test('preparation removes stale runtime variants, preserves unrelated files and is repeatable', (t) => {
  const root = mkdtempSync(path.join(tmpdir(), 'kotoba-runtime-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const source = path.join(root, 'source');
  const destination = path.join(root, 'public');
  mkdirSync(source);
  mkdirSync(destination);
  for (const name of runtime.RUNTIME_FILES) writeFileSync(path.join(source, name), name);
  writeFileSync(path.join(destination, 'ort-wasm-simd-threaded.wasm'), 'unused');
  writeFileSync(path.join(destination, 'ort-wasm-simd-threaded.mjs'), 'unused');
  writeFileSync(path.join(destination, 'keep.txt'), 'not generated by this script');
  runtime.copyRuntime(source, destination);
  runtime.copyRuntime(source, destination);
  assert.deepEqual(readdirSync(destination).sort(), ['keep.txt', ...runtime.RUNTIME_FILES].sort());
  for (const name of runtime.RUNTIME_FILES) assert.equal(readFileSync(path.join(destination, name), 'utf8'), name);
  rmSync(path.join(source, runtime.RUNTIME_FILES[1]));
  assert.throws(() => runtime.copyRuntime(source, destination), /ENOENT/);
});

test('built package verification rejects duplicate WASM and altered glue', (t) => {
  const root = mkdtempSync(path.join(tmpdir(), 'kotoba-runtime-package-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  runtime.copyRuntime(runtime.runtimeDirectory(), path.join(root, 'offline-runtime'));
  assert.equal(verifier.verify(root).runtimeFiles.length, 2);
  mkdirSync(path.join(root, 'assets'));
  const duplicate = path.join(root, 'assets/ort-wasm-simd-threaded.jsep-hash.wasm');
  writeFileSync(duplicate, 'redundant Vite asset');
  assert.throws(() => verifier.verify(root), /Duplicate ONNX assets/);
  rmSync(duplicate);
  writeFileSync(path.join(root, 'offline-runtime', runtime.RUNTIME_FILES[0]), 'wrong version');
  assert.throws(() => verifier.verify(root), /differs from pinned dependency/);
});
